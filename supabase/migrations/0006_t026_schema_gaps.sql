ALTER TABLE public.shipping_usage
    ADD COLUMN IF NOT EXISTS driver_name text,
    ADD COLUMN IF NOT EXISTS driver_phone text,
    ADD COLUMN IF NOT EXISTS delivery_payment_status text
        CHECK (delivery_payment_status IS NULL OR delivery_payment_status IN ('unpaid', 'paid')),
    ADD COLUMN IF NOT EXISTS delivery_payment_amount numeric
        CHECK (delivery_payment_amount IS NULL OR delivery_payment_amount >= 0);

COMMENT ON COLUMN public.shipping_usage.driver_name IS
    'Nombre del conductor asignado al despacho. T-026 gap 2.';
COMMENT ON COLUMN public.shipping_usage.delivery_payment_status IS
    'Estado del pago del despacho (unpaid/paid), independiente del pago de la orden. T-026 gap 2.';

-- =========================================================================
-- Gap 3 — acquisition_cost on serialised_assets (cost per physical unit). No grant change: the
