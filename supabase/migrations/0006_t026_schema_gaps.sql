ALTER TABLE public.serialised_assets
    ADD COLUMN IF NOT EXISTS acquisition_cost numeric
        CHECK (acquisition_cost IS NULL OR acquisition_cost >= 0);

COMMENT ON COLUMN public.serialised_assets.acquisition_cost IS
    'Costo de adquisicion del activo fisico, para margen/ROI. T-026 gap 3 (Opcion A, alcance minimo).';

-- =========================================================================
-- Gap 3 — expenses (operational spend not tied to a single physical unit's acquisition).
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.expenses (
    id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    -- CATEGORY VOCABULARY (R1-001). English tokens (code), Spanish labels (UI), per the project
    -- convention (see 0004's condition vocabulary). Sourced from the canonical Rentabilidad
    -- `#g-cat` <select> (Gastos Fijos: Bodega, Internet, Sueldos, Contador, Software, Hosting;
    -- Gastos Variables: Delivery, Transporte, Mantención, Reparación, Insumos) — not an invented
    -- list. Fixed/variable is a UI grouping in the canonical, not a DB column: nothing downstream
    -- of `expenses` needs to distinguish fixed from variable spend, so it is left for the read
    -- layer (UI groups the 11 values into the same two headings) rather than added as a second
    -- enum column with no consumer.
    category         text        NOT NULL CHECK (category IN (
                         'warehouse', 'internet', 'payroll', 'accounting', 'software', 'hosting',
                         'delivery', 'transport', 'maintenance', 'repair', 'supplies'
                     )),
    amount           numeric     NOT NULL CHECK (amount >= 0),
    expense_date     date        NOT NULL,
    related_order_id integer     REFERENCES public.orders(id) ON DELETE SET NULL,
    related_asset_id bigint      REFERENCES public.serialised_assets(id) ON DELETE SET NULL,
    notes            text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);

-- ON DELETE SET NULL, unlike asset_movements/serialised_assets's RESTRICT: an expense is a
-- financial record that must survive the order or asset it references being deleted (the spend
-- already happened), so it degrades to an unlinked expense rather than blocking the delete.

COMMENT ON TABLE public.expenses IS
    'Operational expense not tied to a single asset acquisition (maintenance, transport, etc). T-026 gap 3, Opcion A minimal scope.';

CREATE INDEX IF NOT EXISTS expenses_expense_date_idx
    ON public.expenses (expense_date);

CREATE INDEX IF NOT EXISTS expenses_related_order_id_idx
    ON public.expenses (related_order_id) WHERE related_order_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS expenses_related_asset_id_idx
    ON public.expenses (related_asset_id) WHERE related_asset_id IS NOT NULL;

DROP TRIGGER IF EXISTS expenses_set_updated_at ON public.expenses;
CREATE TRIGGER expenses_set_updated_at
    BEFORE UPDATE ON public.expenses
    FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

REVOKE ALL ON TABLE public.expenses FROM PUBLIC;
REVOKE ALL ON TABLE public.expenses FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.expenses TO service_role;

ALTER TABLE public.expenses ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow service_role full access to expenses" ON public.expenses;
CREATE POLICY "Allow service_role full access to expenses"
    ON public.expenses
    FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

COMMIT;

