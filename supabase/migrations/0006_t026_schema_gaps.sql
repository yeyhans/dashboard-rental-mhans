-- Gap 2 — driver + delivery payment on shipping_usage (nullable, one driver/one payment per
-- delivery per the user's decision). No grant/RLS change: shipping_usage already has RLS enabled
-- and its grants defined by 0000_baseline.sql / prior migrations; adding nullable columns does not
-- widen any existing grantee's surface.
